// Discovers self-describing built-in pattern modules (`src/sketches/**/*.pattern.js`)
// and emits a static ESM import module consumed by Node and the Vite browser build
// alike. Only `*.pattern.js` files are scanned: this tree also holds helpers and
// historical multi-pattern implementations that must never be auto-registered.
//
// Each discovered module must export a named `pattern` descriptor whose `id`
// matches the file basename (`<id>.pattern.js`). The generated module records the
// repository-relative source path beside every descriptor for diagnostics.
//
// The generator is deterministic (sorted paths), atomic (temp file + rename so
// parallel workers never observe a partial module), idempotent (no rewrite when
// content is unchanged), and loud (missing exports/import errors surface at
// catalog import, never as a silently smaller library).
import { readdir, readFile, writeFile, rename, mkdir, stat } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PATTERN_GLOB_SUFFIX = '.pattern.js';
export const SKETCHES_DIR = 'src/sketches';
export const GENERATED_DIR = 'src/patterns/.generated';
export const GENERATED_FILE = 'discovered.js';

function repoRoot(cwd = process.cwd()) {
  return resolve(cwd);
}

function toPosix(path) {
  return path.split(sep).join('/');
}

async function walk(dir, out) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      // Never descend into node_modules or dot-directories.
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
      await walk(full, out);
    } else if (entry.isFile() && entry.name.endsWith(PATTERN_GLOB_SUFFIX)) {
      out.push(full);
    }
  }
  return out;
}

/** Recursively list `*.pattern.js` files under `src/sketches`, sorted, repo-relative (posix). */
export async function discoverPatternFiles(root = repoRoot()) {
  const base = join(root, SKETCHES_DIR);
  try {
    await stat(base);
  } catch {
    return [];
  }
  const found = await walk(base, []);
  return found.map((full) => toPosix(relative(root, full))).sort();
}

function identifierFor(index) {
  return `discovered${index}`;
}

/** Render the generated module source for the given sorted repo-relative paths. */
export function renderDiscoveredModule(paths) {
  const lines = [
    '// AUTO-GENERATED by scripts/generate-pattern-catalog.mjs — do not edit.',
    '// Regenerated automatically by Vite and Playwright config hooks; the file is',
    '// git-ignored and recreated from a clean checkout.',
    '',
  ];
  paths.forEach((path, index) => {
    // discovered.js lives at src/patterns/.generated/, so module specifiers are
    // relative to that directory (e.g. ../../sketches/x.pattern.js).
    const fromGeneratedDir = toPosix(relative(join(GENERATED_DIR), path));
    const specifier = fromGeneratedDir.startsWith('.') ? fromGeneratedDir : `./${fromGeneratedDir}`;
    lines.push(`import { pattern as ${identifierFor(index)} } from '${specifier}';`);
  });
  lines.push('');
  lines.push('/** Discovered built-in descriptors: { path, pattern } in stable path order. */');
  lines.push('export const DISCOVERED_PATTERNS = [');
  paths.forEach((path, index) => {
    lines.push(`  { path: ${JSON.stringify(path)}, pattern: ${identifierFor(index)} },`);
  });
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

/**
 * Regenerate `src/patterns/.generated/discovered.js`. Returns
 * `{ paths, changed, file }`. Never throws for an empty catalog: zero
 * discovered modules is a valid state (legacy-only library).
 */
export async function generatePatternCatalog(root = repoRoot()) {
  const paths = await discoverPatternFiles(root);
  const source = renderDiscoveredModule(paths);
  const dir = join(root, GENERATED_DIR);
  const file = join(dir, GENERATED_FILE);
  await mkdir(dir, { recursive: true });
  let previous = null;
  try {
    previous = await readFile(file, 'utf8');
  } catch {
    previous = null;
  }
  if (previous === source) return { paths, changed: false, file };
  // Atomic replace: concurrent workers (dev server + test collection) must
  // never import a partially written module.
  const tmp = `${file}.${process.pid}.tmp`;
  await writeFile(tmp, source, 'utf8');
  await rename(tmp, file);
  return { paths, changed: true, file };
}

/** Synchronous best-effort preparation for config hooks (import first, then call). */
export async function ensurePatternCatalog(root = repoRoot()) {
  return generatePatternCatalog(root);
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const { paths, changed, file } = await generatePatternCatalog();
  console.log(`${changed ? 'wrote' : 'unchanged'} ${toPosix(relative(process.cwd(), file))} (${paths.length} pattern module${paths.length === 1 ? '' : 's'})`);
}
